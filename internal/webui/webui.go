// Package webui serves the React (shadcn/ui) single-page app.
//
// The production build of web/ (web/dist) is copied to internal/webui/dist by
// `make web` / the Dockerfile and embedded into the binary. When the SPA has
// not been built (plain `go build ./...` without node) a small placeholder
// page is served instead, so the module always compiles.
//
// Behaviour (docs/ARCHITECTURE.md §5, Kutt server.js:54-56):
//
//   - /images/* and /css/* are looked up in the operator's custom directory
//     (cfg.StaticDir, default "custom") first, exactly like Kutt's
//     express.static("custom/images") / ("custom/css", {extensions:["css"]}).
//     Every custom/css/*.css file is also linked from index.html, mirroring
//     Kutt's `custom_styles` layout locals.
//   - Hashed build output under /assets/ is served with a one-year immutable
//     Cache-Control; index.html with no-cache; other files with a short TTL.
//   - Precompressed .br / .gz siblings (generated by web/scripts/compress.mjs)
//     are served when the client's Accept-Encoding allows.
//   - Unknown extension-less paths (client-side routes such as /settings or
//     /verify/:token) fall back to index.html; unknown asset-like paths 404.
package webui

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"html"
	"io/fs"
	"mime"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/Hulul-Group/Tusk/internal/config"
)

//go:embed all:dist
var embedded embed.FS

// Cache-Control values.
const (
	cacheImmutable = "public, max-age=31536000, immutable"
	cacheIndex     = "no-cache"
	cacheDefault   = "public, max-age=3600"
	cacheCustom    = "public, max-age=300"
)

// customCSSMarker is replaced in index.html with <link> tags for custom/css/*.css.
const customCSSMarker = "<!--tusk:custom-css-->"

// SPARoutes lists the client-side routes rendered by the SPA. The HTTP router
// must send these (plus the asset prefixes in AssetPrefixes) to Handler, and
// everything else that looks like /{id} to the redirector. Patterns use Go
// 1.22 ServeMux syntax.
var SPARoutes = []string{
	"/{$}",
	"/login",
	"/create-admin",
	"/settings",
	"/admin",
	"/stats",
	"/report",
	"/terms",
	"/banned",
	"/404",
	"/reset-password",
	"/reset-password/{token}",
	"/verify/{token}",
	"/verify-email/{token}",
}

// AssetPrefixes are static file locations served by Handler.
var AssetPrefixes = []string{
	"/assets/",
	"/images/",
	"/css/",
	"/fonts/",
	"/favicon.ico",
	"/robots.txt",
	"/manifest.webmanifest",
}

type file struct {
	data     []byte
	gz       []byte // nil when no smaller gzip exists
	br       []byte // nil when no smaller brotli exists
	etag     string
	ctype    string
	cache    string
	compress bool // content type benefits from compression → Vary header
}

type handler struct {
	files     map[string]*file // key: clean path without leading slash, e.g. "assets/index-abc.js"
	index     *file
	customDir string
	modTime   time.Time
}

// Handler returns the SPA handler. cfg may be nil (no custom dir, default site name).
func Handler(cfg *config.Config) http.Handler {
	sub, err := fs.Sub(embedded, "dist")
	if err != nil {
		panic(err) // impossible: the directory is embedded at compile time
	}
	return newHandler(sub, cfg)
}

func newHandler(dist fs.FS, cfg *config.Config) *handler {
	h := &handler{files: map[string]*file{}, modTime: time.Now()}
	siteName := "Kutt"
	if cfg != nil {
		h.customDir = cfg.StaticDir
		if cfg.SiteName != "" {
			siteName = cfg.SiteName
		}
	}

	_ = fs.WalkDir(dist, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if strings.HasSuffix(p, ".gz") || strings.HasSuffix(p, ".br") || path.Base(p) == ".gitignore" {
			return nil
		}
		data, err := fs.ReadFile(dist, p)
		if err != nil {
			return nil
		}
		f := newFile(p, data)
		if b, err := fs.ReadFile(dist, p+".gz"); err == nil && len(b) < len(data) {
			f.gz = b
		}
		if b, err := fs.ReadFile(dist, p+".br"); err == nil && len(b) < len(data) {
			f.br = b
		}
		h.files[p] = f
		return nil
	})

	indexHTML := placeholderHTML
	if f, ok := h.files["index.html"]; ok {
		indexHTML = f.data
	}
	h.index = h.renderIndex(indexHTML, siteName)
	h.files["index.html"] = h.index
	return h
}

func newFile(p string, data []byte) *file {
	sum := sha256.Sum256(data)
	ct := mime.TypeByExtension(path.Ext(p))
	if ct == "" {
		ct = http.DetectContentType(data)
	}
	f := &file{
		data:     data,
		etag:     `"` + hex.EncodeToString(sum[:12]) + `"`,
		ctype:    ct,
		cache:    cacheDefault,
		compress: compressible(ct),
	}
	if strings.HasPrefix(p, "assets/") {
		f.cache = cacheImmutable
	}
	return f
}

// renderIndex injects the site name and custom stylesheet links. The result is
// computed once at startup (Kutt also reads custom/css once at boot).
func (h *handler) renderIndex(src []byte, siteName string) *file {
	out := bytes.Replace(src, []byte("<title>Kutt</title>"),
		[]byte("<title>"+html.EscapeString(siteName)+"</title>"), 1)

	var links strings.Builder
	for _, name := range h.customCSS() {
		links.WriteString(`<link rel="stylesheet" href="/css/`)
		links.WriteString(html.EscapeString(name))
		links.WriteString(`">`)
	}
	out = bytes.Replace(out, []byte(customCSSMarker), []byte(links.String()), 1)

	f := newFile("index.html", out)
	f.cache = cacheIndex
	var buf bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	_, _ = zw.Write(out)
	_ = zw.Close()
	if buf.Len() < len(out) {
		f.gz = buf.Bytes()
	}
	return f
}

// customCSS returns the sorted *.css file names in <customDir>/css.
func (h *handler) customCSS() []string {
	if h.customDir == "" {
		return nil
	}
	entries, err := os.ReadDir(filepath.Join(h.customDir, "css"))
	if err != nil {
		return nil
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(strings.ToLower(e.Name()), ".css") {
			out = append(out, e.Name())
		}
	}
	sort.Strings(out)
	return out
}

func (h *handler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		w.Header().Set("Allow", "GET, HEAD")
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	p := path.Clean("/" + r.URL.Path)
	rel := strings.TrimPrefix(p, "/")

	if strings.HasPrefix(p, "/api/") || p == "/api" {
		http.NotFound(w, r)
		return
	}

	// 1. Operator overrides (custom/images, custom/css) win over embedded files.
	if h.serveCustom(w, r, rel) {
		return
	}

	// 2. Embedded build output.
	if rel == "" {
		rel = "index.html"
	}
	if f, ok := h.files[rel]; ok {
		h.serveFile(w, r, f)
		return
	}

	// 3. SPA fallback for client routes; real 404 for missing assets.
	if strings.HasPrefix(p, "/assets/") || !wantsHTML(r, p) {
		http.NotFound(w, r)
		return
	}
	h.serveFile(w, r, h.index)
}

// serveCustom serves /images/* from <custom>/images and /css/* from <custom>/css
// (with Kutt's implicit ".css" extension). Reports whether it wrote a response.
func (h *handler) serveCustom(w http.ResponseWriter, r *http.Request, rel string) bool {
	if h.customDir == "" {
		return false
	}
	var sub, name string
	switch {
	case strings.HasPrefix(rel, "images/"):
		sub, name = "images", strings.TrimPrefix(rel, "images/")
	case strings.HasPrefix(rel, "css/"):
		sub, name = "css", strings.TrimPrefix(rel, "css/")
	default:
		return false
	}
	if name == "" || strings.Contains(name, "..") {
		return false
	}
	base := filepath.Join(h.customDir, sub)
	candidates := []string{filepath.Join(base, filepath.FromSlash(name))}
	if sub == "css" && path.Ext(name) == "" {
		candidates = append(candidates, candidates[0]+".css")
	}
	for _, c := range candidates {
		// Stay inside the custom directory even with symlink-free traversal attempts.
		if !strings.HasPrefix(c, filepath.Clean(base)+string(filepath.Separator)) {
			continue
		}
		fh, err := os.Open(c)
		if err != nil {
			continue
		}
		st, err := fh.Stat()
		if err != nil || st.IsDir() {
			_ = fh.Close()
			continue
		}
		if ct := mime.TypeByExtension(filepath.Ext(c)); ct != "" {
			w.Header().Set("Content-Type", ct)
		}
		w.Header().Set("Cache-Control", cacheCustom)
		http.ServeContent(w, r, st.Name(), st.ModTime(), fh)
		_ = fh.Close()
		return true
	}
	return false
}

func (h *handler) serveFile(w http.ResponseWriter, r *http.Request, f *file) {
	hd := w.Header()
	hd.Set("Content-Type", f.ctype)
	hd.Set("Cache-Control", f.cache)
	hd.Set("ETag", f.etag)
	hd.Set("X-Content-Type-Options", "nosniff")
	if f.compress {
		hd.Add("Vary", "Accept-Encoding")
	}

	body := f.data
	if enc, b := pickEncoding(r.Header.Get("Accept-Encoding"), f); enc != "" {
		hd.Set("Content-Encoding", enc)
		body = b
	}
	// ServeContent handles If-None-Match (ETag), HEAD and Range. Range on an
	// encoded body is a range of the encoded bytes, which is what RFC 9110 says.
	http.ServeContent(w, r, "", h.modTime, bytes.NewReader(body))
}

// pickEncoding chooses br, then gzip, honouring q=0 exclusions.
func pickEncoding(accept string, f *file) (string, []byte) {
	if accept == "" || (f.br == nil && f.gz == nil) {
		return "", nil
	}
	q := parseAcceptEncoding(accept)
	allowed := func(enc string) bool {
		if v, ok := q[enc]; ok {
			return v > 0
		}
		if v, ok := q["*"]; ok {
			return v > 0
		}
		return false
	}
	if f.br != nil && allowed("br") {
		return "br", f.br
	}
	if f.gz != nil && allowed("gzip") {
		return "gzip", f.gz
	}
	return "", nil
}

func parseAcceptEncoding(s string) map[string]float64 {
	out := map[string]float64{}
	for _, part := range strings.Split(s, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		name, params, _ := strings.Cut(part, ";")
		name = strings.ToLower(strings.TrimSpace(name))
		qv := 1.0
		for _, p := range strings.Split(params, ";") {
			k, v, ok := strings.Cut(strings.TrimSpace(p), "=")
			if ok && strings.EqualFold(strings.TrimSpace(k), "q") {
				if f, err := strconv.ParseFloat(strings.TrimSpace(v), 64); err == nil {
					qv = f
				}
			}
		}
		out[name] = qv
	}
	return out
}

// wantsHTML reports whether an unknown path should get the SPA shell: either
// the last segment has no file extension, or the client explicitly asks for HTML.
func wantsHTML(r *http.Request, p string) bool {
	if path.Ext(path.Base(p)) == "" {
		return true
	}
	return strings.Contains(r.Header.Get("Accept"), "text/html")
}

func compressible(ct string) bool {
	switch {
	case strings.HasPrefix(ct, "text/"),
		strings.Contains(ct, "javascript"),
		strings.Contains(ct, "json"),
		strings.Contains(ct, "xml"),
		strings.Contains(ct, "svg"),
		strings.HasPrefix(ct, "image/x-icon"),
		strings.HasPrefix(ct, "image/vnd.microsoft.icon"):
		return true
	}
	return false
}

// placeholderHTML is served when the SPA was not built into the binary.
var placeholderHTML = []byte(`<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Kutt</title>` + customCSSMarker + `</head>
<body style="font-family:system-ui,sans-serif;max-width:40rem;margin:4rem auto;padding:0 1rem;line-height:1.5">
<h1>Tusk</h1>
<p>The web UI was not built into this binary. Run <code>make web build</code> (or build the Docker image).
Short links and the <code>/api/v2</code> API work without it.</p>
</body></html>
`)
